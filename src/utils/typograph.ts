/**
 * Минимальная типографика для русского текста, как в макете:
 * короткие слова (предлоги, союзы, частицы) привязываются неразрывным пробелом к следующему слову.
 */
const SHORT_WORD = /(^|[\s(«])([а-яёА-ЯЁ]{1,2}|[A-Za-z]{1,2})\s+/g;

export function typograph(text: string): string {
  // два прохода — для цепочек коротких слов («и в банке»)
  return text.replace(SHORT_WORD, '$1$2 ').replace(SHORT_WORD, '$1$2 ');
}
